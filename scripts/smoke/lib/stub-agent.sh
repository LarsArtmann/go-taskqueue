#!/usr/bin/env bash
# scripts/smoke/lib/stub-agent.sh — shared stub-agent factory for the
# repo-surface smokes (status-loop, dogfood-once, redaction, status-rewind).
#
# Each smoke hand-rolled the same stub prologue (prompt-after-`--` parse)
# and the same verdict rail; when the stdout rail was retired (dcd2d542)
# all four rotted independently — this lib is the single home so the next
# rail change is one edit (stub-lib extraction row).
#
# Usage inside a smoke (after REPO_ROOT is set):
#   . "$REPO_ROOT/scripts/smoke/lib/stub-agent.sh"
#   STUB="$TMP/stub-agent"
#   { stub_agent_prologue
#     cat <<'EOF'
#   case "$prompt" in
#       ...
#   esac
#   EOF
#   } >"$STUB"
#   stub_agent_install "$STUB"
#
# --self-test pins the prologue contract (fleet convention: shared fixtures
# carry their own pins, not folklore).

stub_agent_prologue() {
	cat <<'EOF'
#!/bin/sh
# prologue generated by scripts/smoke/lib/stub-agent.sh — DO NOT hand-roll
# (single home for the prompt parse + the verdict rail; dcd2d542 dropped the
# stdout fallback, stubs must not print verdicts to stdout).
prompt=""
prev=""
for a in "$@"; do
	[ "$prev" = "--" ] && prompt="$a"
	prev="$a"
done
stub_verdict() {
	if [ -z "${TQ_RESULT_FILE:-}" ]; then
		echo "stub_verdict: TQ_RESULT_FILE unset — the verdict rail is FILE-ONLY" >&2
		exit 3
	fi
	printf '%s\n' "$1" >"$TQ_RESULT_FILE"
}
EOF
}

stub_agent_install() {
	local path="${1:-}"
	[ -n "$path" ] && [ -f "$path" ] || {
		echo "stub_agent_install: need the stub path" >&2
		return 1
	}
	chmod +x "$path"
	export TQ_AGENT_BIN="$path"
}

if [ "${1:-}" = "--self-test" ]; then
	set -euo pipefail
	tmp="$(mktemp -d)"
	trap 'rm -rf "$tmp"' EXIT
	stub="$tmp/stub"
	{
		stub_agent_prologue
		cat <<'EOF'
case "$prompt" in
	*"do work"*)
		printf 'did the work\n'
		stub_verdict '{"summary":"stub"}'
		;;
	*)
		echo "unknown prompt: $prompt" >&2
		exit 4
		;;
esac
EOF
	} >"$stub"
	stub_agent_install "$stub"
	out="$(TQ_RESULT_FILE="$tmp/res.json" "$stub" --payload '{"repo":"r"}' -- 'please do work now' 2>&1)"
	grep -q 'did the work' <<<"$out" || {
		echo "FAIL: work branch stdout missing: $out"
		exit 1
	}
	grep -qF '{"summary":"stub"}' "$tmp/res.json" || {
		echo "FAIL: verdict did not land in TQ_RESULT_FILE"
		exit 1
	}
	rc=0
	env -u TQ_RESULT_FILE "$stub" -- 'please do work now' >/dev/null 2>&1 || rc=$?
	[ "$rc" -eq 3 ] || {
		echo "FAIL: unset-rail refusal rc=$rc (want 3 — the FILE-ONLY contract)"
		exit 1
	}
	exported="$(bash -c '. "$1"; stub_agent_install "$2"; printf %s "${TQ_AGENT_BIN:-}"' _ "$0" "$stub")"
	[ "$exported" = "$stub" ] || {
		echo "FAIL: stub_agent_install did not export TQ_AGENT_BIN (got: $exported)"
		exit 1
	}
	echo "stub-agent lib self-test ok (prompt parse + file-only verdict rail + install export)"
	exit 0
fi
